-- 3. Display all sales records
SELECT *
FROM sales;


-- 4. Calculate total revenue
SELECT
    SUM(quantity * price) AS Total_Revenue
FROM sales;


-- 5. Calculate total number of orders
SELECT
    COUNT(*) AS Total_Orders
FROM sales;


-- 6. Find revenue by product category
SELECT
    category,
    SUM(quantity * price) AS Total_Revenue
FROM sales
GROUP BY category
ORDER BY Total_Revenue DESC;


-- 7. Find top 5 products by revenue
SELECT
    product_name,
    SUM(quantity * price) AS Product_Revenue
FROM sales
GROUP BY product_name
ORDER BY Product_Revenue DESC
LIMIT 5;


-- 8. Find revenue generated by each customer
SELECT
    customer_name,
    SUM(quantity * price) AS Customer_Revenue
FROM sales
GROUP BY customer_name
ORDER BY Customer_Revenue DESC;


-- 9. Calculate monthly revenue
SELECT
    MONTH(sale_date) AS Sale_Month,
    SUM(quantity * price) AS Monthly_Revenue
FROM sales
GROUP BY MONTH(sale_date)
ORDER BY Sale_Month;


-- 10. Classify orders by revenue
SELECT
    sale_id,
    product_name,
    quantity * price AS Order_Revenue,
    CASE
        WHEN quantity * price >= 50000 THEN 'High Value'
        WHEN quantity * price >= 10000 THEN 'Medium Value'
        ELSE 'Low Value'
    END AS Order_Category
FROM sales
ORDER BY Order_Revenue DESC;


-- 11. Find orders above average order value
SELECT
    sale_id,
    customer_name,
    product_name,
    quantity * price AS Order_Revenue
FROM sales
WHERE quantity * price > (
    SELECT AVG(quantity * price)
    FROM sales
)
ORDER BY Order_Revenue DESC;


-- 12. Rank products by revenue
WITH Product_Sales AS (
    SELECT
        product_name,
        SUM(quantity * price) AS Total_Revenue
    FROM sales
    GROUP BY product_name
)
SELECT
    product_name,
    Total_Revenue,
    DENSE_RANK() OVER (
        ORDER BY Total_Revenue DESC
    ) AS Revenue_Rank
FROM Product_Sales;


-- 13. Find the highest revenue order
SELECT
    sale_id,
    customer_name,
    product_name,
    quantity * price AS Order_Revenue
FROM sales
ORDER BY Order_Revenue DESC
LIMIT 1;
